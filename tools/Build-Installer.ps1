# Generates build/Install.luau: run it in Studio (Edit mode, command bar or MCP execute_luau)
# to install every game script and rebuild the map with its edit-time preview.
param([string]$OutputPath = 'build/Install.luau')
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path $PSScriptRoot -Parent
. (Join-Path $PSScriptRoot 'Sources.ps1')

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('-- Generated by tools/Build-Installer.ps1 from src/. Run in Studio Edit mode only.')
$lines.Add('assert(not game:GetService("RunService"):IsRunning(), "Stop Play before installing")')
$lines.Add('local function resolve(path)')
$lines.Add('	local node = game')
$lines.Add('	for part in path:gmatch("[^%.]+") do')
$lines.Add('		local child = if node == game then game:GetService(part) else node:FindFirstChild(part)')
$lines.Add('		if not child then child = Instance.new("Folder"); child.Name = part; child.Parent = node end')
$lines.Add('		node = child')
$lines.Add('	end')
$lines.Add('	return node')
$lines.Add('end')
$lines.Add('local function install(parentPath, name, class, source)')
$lines.Add('	local parent = resolve(parentPath)')
$lines.Add('	local script = parent:FindFirstChild(name)')
$lines.Add('	if script and script.ClassName ~= class then error("Conflicting instance: " .. script:GetFullName()) end')
$lines.Add('	if not script then script = Instance.new(class); script.Name = name; script.Parent = parent end')
$lines.Add('	script.Source = source')
$lines.Add('end')
foreach ($entry in $GameSources) {
    $source = [IO.File]::ReadAllText((Join-Path $projectRoot $entry.Path)).Replace("`r`n", "`n")
    if ($source.Contains(']==========]')) { throw "Source delimiter conflict in $($entry.Path)" }
    $lines.Add(('install("{0}", "{1}", "{2}", [==========[{3}]==========])' -f $entry.Parent, $entry.Name, $entry.Class, $source))
}
$lines.Add('workspace.StreamingEnabled = false -- client-side world labels and animation expect the whole map')
$lines.Add('local old = workspace:FindFirstChild("MonsterEggEscape")')
$lines.Add('if old then old:Destroy() end')
$lines.Add('-- Require a fresh copy so Studio does not reuse cached module results.')
$lines.Add('local copy = game.ReplicatedStorage.MonsterEgg:Clone()')
$lines.Add('copy.Parent = game:GetService("ServerStorage")')
$lines.Add('local ok, err = pcall(function()')
$lines.Add('	local World = require(copy.World)')
$lines.Add('	World.Preview(World.Build())')
$lines.Add('end)')
$lines.Add('copy:Destroy()')
$lines.Add('assert(ok, err)')
$lines.Add('return { installed = true, objects = #workspace.MonsterEggEscape:GetDescendants() }')

$target = Join-Path $projectRoot $OutputPath
[IO.Directory]::CreateDirectory((Split-Path $target -Parent)) | Out-Null
[IO.File]::WriteAllText($target, ($lines -join "`n"), [Text.UTF8Encoding]::new($false))
Write-Output "Installer written: $target"
